#ifndef _aspect_adjoint_operators_artificial_viscosity_adjoint_h
#define _aspect_adjoint_operators_artificial_viscosity_adjoint_h

#include <aspect/adjoint/core/state.h>
#include <aspect/advection_field.h>
#include <aspect/global.h>
#include <aspect/simulator_access.h>

#include <vector>

namespace aspect
{
  template <int dim> class Simulator;

  namespace Adjoint
  {
    template <int dim> class AdvectionAdjointCalculator;

    /**
     * Reverse-mode helper for the entropy-viscosity stabilization coefficient
     * used by finite-element advection equations.
     *
     * The forward advection residual sees artificial viscosity in two layers:
     * first the residual contains a cellwise diffusion coefficient
     * \f$\nu_{\mathrm{art},K}\f$, and second that coefficient is produced by
     * the entropy-viscosity estimator from old field values, old velocities,
     * extrema, and residual norms. The time-dependent adjoint reverses those
     * layers in the opposite order:
     *
     * - assemble_coefficient_seed() computes the seed
     *   \f$\bar\nu_{\mathrm{art},K}\f$ generated by the diffusion term after
     *   the transposed advection equation has been solved.
     * - add_estimator_transpose() propagates that seed through the supported
     *   active branches of the entropy-viscosity estimator to q_{n-1},
     *   q_{n-2}, and Stokes adjoint right hand sides.
     *
     * The current implementation assumes that each active cell stays on a
     * single branch of \f$\max(k,\nu_{\mathrm{art}})\f$ for all quadrature
     * points. Mixed branch cells need an additional quadrature-point active
     * set cache before their exact transpose can be enabled.
     */
    template <int dim>
    class ArtificialViscosityAdjoint : public SimulatorAccess<dim>
    {
      public:
        explicit
        ArtificialViscosityAdjoint(Simulator<dim> &simulator);

        /**
         * Assemble the cellwise adjoint seed for the artificial-viscosity
         * coefficient at @p snapshot:
         *
         * \f[
         * \bar\nu_{\mathrm{art},K}
         * =
         * -\Delta t
         * \int_K \chi_{\nu,Kq}\nabla z\cdot\nabla T\,d\Omega.
         * \f]
         *
         * The returned vector is indexed by active cell index. Entries for
         * non-locally-owned cells are left at zero.
         */
        std::vector<double>
        assemble_coefficient_seed(const AdvectionField &advection_field,
                                  const ForwardStateView<dim> &snapshot,
                                  const LinearAlgebra::BlockVector &transpose_solution) const;

        /**
         * Reverse the supported active branches of the entropy-viscosity
         * estimator and add their contributions to the older time levels.
         *
         * @p coefficient_seed is indexed by active cell and represents
         * \f$\bar\nu_{\mathrm{art},K}\f$. Field adjoints receive derivatives
         * with respect to old/old-old advected values and their gradients.
         * Stokes right hand sides receive derivatives with respect to old
         * velocities and strain rates. For temperature, the optional
         * composition adjoints receive material-prefactor derivatives created
         * inside the estimator.
         */
        void
        add_estimator_transpose(const AdvectionField &advection_field,
                                const ForwardStateView<dim> &snapshot,
                                const std::vector<double> &coefficient_seed,
                                LinearAlgebra::BlockVector &previous_field_adjoint,
                                LinearAlgebra::BlockVector *previous_previous_field_adjoint,
                                LinearAlgebra::BlockVector &previous_stokes_adjoint_rhs,
                                LinearAlgebra::BlockVector *previous_previous_stokes_adjoint_rhs,
                                std::vector<LinearAlgebra::BlockVector> *previous_composition_adjoints = nullptr,
                                std::vector<LinearAlgebra::BlockVector> *previous_previous_composition_adjoints = nullptr) const;

      private:
        friend class AdvectionAdjointCalculator<dim>;

        /**
         * Run a local finite-difference dot-product diagnostic for the
         * derivative of the assembled advection residual with respect to an
         * independent cellwise artificial-viscosity coefficient. This isolates
         * the R_q -> nu_art layer from the entropy-viscosity estimator itself.
         */
        void
        run_coefficient_seed_diagnostic(const AdvectionField &advection_field,
                                        const ForwardStateView<dim> &snapshot,
                                        const LinearAlgebra::BlockVector &transpose_solution,
                                        const std::vector<double> &coefficient_seed,
                                        const double epsilon) const;

        /**
         * Run a finite-difference dot-product diagnostic for the currently
         * implemented transpose of the entropy-viscosity estimator. The test
         * starts from an artificial cellwise seed @f$\bar\nu_{\rm art}@f$ and
         * compares add_estimator_transpose() with a recomputation of the
         * forward estimator under perturbations of old/old-old field and
         * velocity states.
         */
        void
        run_estimator_transpose_diagnostic(const AdvectionField &advection_field,
                                           const ForwardStateView<dim> &snapshot,
                                           const double epsilon) const;

        /**
         * Run a frozen-denominator diagnostic for the local
         * max-residual/entropy-deviation numerator of the alpha=2
         * entropy-viscosity estimator.
         */
        void
        run_local_entropy_residual_transpose_diagnostic(const AdvectionField &advection_field,
                                                        const ForwardStateView<dim> &snapshot,
                                                        const double epsilon) const;

        /**
         * Run a scalar diagnostic for the denominator derivative
         * nu_entropy = c_R h^2 Rmax / global_entropy_variation.
         */
        void
        run_global_entropy_denominator_scalar_diagnostic(const AdvectionField &advection_field,
                                                         const ForwardStateView<dim> &snapshot,
                                                         const double epsilon) const;

        /**
         * Run a standalone diagnostic for
         * global_entropy_variation(field_history), keeping average_field
         * frozen at the value supplied by the extrapolated field range.
         */
        void
        run_global_entropy_variation_transpose_diagnostic(const AdvectionField &advection_field,
                                                          const ForwardStateView<dim> &snapshot,
                                                          const double epsilon) const;

        /**
         * Add the transpose of global_entropy_variation(field_history), with
         * average_field frozen at the extrapolated-range value.
         */
        void
        add_global_entropy_variation_transpose(const AdvectionField &advection_field,
                                               const double bar_entropy_variation,
                                               double &bar_average_field,
                                               LinearAlgebra::BlockVector &previous_field_adjoint,
                                               LinearAlgebra::BlockVector *previous_previous_field_adjoint) const;

        /**
         * Add the transpose of
         * average_field = 0.5 * (min(extrapolated field) + max(extrapolated field))
         * to the old/old-old advection field states.
         */
        void
        add_extrapolated_field_average_transpose(const AdvectionField &advection_field,
                                                 const ForwardStateView<dim> &snapshot,
                                                 const double bar_average_field,
                                                 LinearAlgebra::BlockVector &previous_field_adjoint,
                                                 LinearAlgebra::BlockVector *previous_previous_field_adjoint) const;

        Simulator<dim> *simulator;
    };
  }
}

#endif
